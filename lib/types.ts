// Core object model for Manufacturing OS.
//
// This file is the single source of truth for the shape of every domain
// object in the system. The frontend shell currently reads mock data that
// conforms to these types (see lib/mock/*). When Sanity/Postgres-backed
// data is introduced, only lib/data.ts and lib/mock/* should need to
// change -- these types and every component built on them stay put.
//
// UQ-1 resolution (docs/architecture/entity-publishing-system/migration-plan.md,
// resolved by issue #25): this file's `Part` interface below was the
// PRIVATE, RFQ-specific physical part concept (bound to one CAD package /
// revision / RFQ), which collided in name with the PUBLIC "Part" knowledge
// entity introduced by the entity-publishing architecture (see
// lib/content/types.ts). Per the issue's explicit instruction, the private
// concept here is renamed `PartInstance`; `Part` is reserved for the public
// knowledge entity. `PartInstance` may reference a public `Part` by a
// future `contentPartId` field once the internal ops app is wired to the
// content layer -- not added speculatively in this pass.

/** Provenance rule: never treat an AI guess, a marketing claim, verified
 * documentation, a quote and a proven production outcome as equivalent. */
export type SourceType =
  | "ai_inferred"
  | "supplier_marketing"
  | "documentation_verified"
  | "quote_derived"
  | "production_proven"
  | "manual_entry";

export type ConfidenceLevel = "low" | "medium" | "high" | "verified";

export interface Evidence {
  id: string;
  summary: string;
  sourceType: SourceType;
  url?: string;
  capturedAt: string;
}

/** Shared metadata every important object should carry. */
export interface Traceable {
  id: string;
  status: string;
  source: SourceType;
  confidence: ConfidenceLevel;
  revision?: number;
  createdAt: string;
  updatedAt: string;
  owner: string;
  evidence: Evidence[];
  lastVerified?: string;
}

export type DemandStage =
  | "search"
  | "visitor"
  | "cad_rfq"
  | "quote"
  | "paid"
  | "repeat";

/** Distinguishes an externally observed market signal (search volume we do
 * not control) from a signal generated by our own coverage or transactions
 * (our search console, our site analytics, our RFQ/quote/order system), so
 * the two are never confused when reading a demand funnel. */
export type DemandSignalSource =
  | "external_market_estimate"
  | "search_console"
  | "site_analytics"
  | "outbound_research"
  | "rfq_intake"
  | "quote_system"
  | "paid_transaction";

export interface DemandSignal {
  stage: DemandStage;
  value: number;
  unit: string;
  period: string;
  signalSource: DemandSignalSource;
}

