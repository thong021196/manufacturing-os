export type OpportunityStage =
  | "identified"
  | "qualifying"
  | "cad_received"
  | "rfq_active"
  | "quoted"
  | "won"
  | "lost";

export type RiskLevel = "low" | "medium" | "high";

/**
 * Market-level opportunity: Demand x Capability x Competition x Margin x
 * Risk for a market/component combination, independent of any one
 * customer. This is the Discovery-layer "opportunity" the system map
 * describes. It is distinct from a CommercialOpportunity (below), which is
 * a specific customer's deal moving through a sales pipeline. A commercial
 * opportunity may reference the market opportunity that qualified it via
 * `marketOpportunityId`, but the two are never conflated into one object.
 */
export interface MarketOpportunity extends Traceable {
  name: string;
  description: string;
  marketId: string;
  componentIds: string[];
  demandScore: number;
  capabilityScore: number;
  competitionScore: number;
  marginPotentialPct: number;
  riskLevel: RiskLevel;
}

/**
 * Commercial opportunity: a specific customer's deal, tracked through a
 * sales-style pipeline stage. Renamed conceptually from a generic
 * "Opportunity" to make explicit that this is pipeline/deal semantics, not
 * market-level opportunity scoring (see MarketOpportunity above).
 */
export interface Opportunity extends Traceable {
  name: string;
  description: string;
  opportunityType: "commercial";
  marketOpportunityId?: string;
  stage: OpportunityStage;
  marketId: string;
  geographyId: string;
  componentIds: string[];
  estValueUsd: number;
  demandSignals: DemandSignal[];
}

export interface Competitor extends Traceable {
  name: string;
  description: string;
  website?: string;
  marketIds: string[];
  geographyIds: string[];
  strengths: string[];
  weaknesses: string[];
}

